"""과목 이름을 교과군으로 묶는다.

`수학Ⅰ`(2학년)과 `미적분`(3학년)은 학년이 달라서, 학년으로 묶으면 서로 다른
가지에 놓인다. 그러면 정작 보고 싶은 것 — **한 교과가 3년 동안 어떻게 깊어졌나**
— 가 그래프에서 사라진다. 묶는 축은 학년이 아니라 교과다.

    수학 ─┬ 1학년 수학
          ├ 2학년 수학Ⅰ · 2학년 수학Ⅱ
          └ 3학년 미적분 · 3학년 확률과 통계 · 3학년 수학과제 탐구

교과군은 지어낸 분류가 아니라 **고등학교 편제 그대로**다(국어·수학·영어·사회·
과학·체육·예술·기술가정정보·제2외국어한문·교양). 학생이 시간표에서 보던 이름이라
설명이 필요 없다.

규칙은 **위에서부터 먼저 맞는 것**을 쓴다. 순서가 뜻을 가지므로 함부로 섞지 말 것:
`인공지능과 미래사회` 는 '사회' 를 품고 있어서 정보 규칙이 사회보다 위에 있어야
하고, `수학과제 탐구` 는 수학, `사회문제 탐구` 는 사회로 가야 한다. 화면 쪽
아이콘 규칙(`theme/nodeIcons.js`)과 같은 순서를 지킨다.
"""

from __future__ import annotations

import re

# [정규식, 교과군]
_RULES: list[tuple[re.Pattern[str], str]] = [
    # 정보·AI 는 '사회'·'과학' 을 품은 과목명이 많아 가장 먼저 본다.
    (re.compile(r"인공지능|머신러닝|딥러닝|빅데이터|데이터\s*분석"), "기술·정보"),
    (re.compile(r"정보|컴퓨터|프로그래밍|피지컬|코딩|소프트웨어|알고리즘|기술[·・]?가정|공학"), "기술·정보"),

    (re.compile(r"수학|미적분|확률|통계|기하|해석"), "수학"),
    (re.compile(r"물리|화학|생명과학|생물|지구과학|과학"), "과학"),

    # '법과' 를 그냥 쓰면 "화법과 작문" 이 걸린다. 과목명 꼴로만 잡는다.
    (re.compile(r"한국사|세계사|동아시아사|역사"), "사회"),
    (re.compile(r"사회|정치|경제|지리|정치와\s*법|윤리|철학|종교|심리|교육학|논리"), "사회"),

    (re.compile(r"영어"), "영어"),
    (re.compile(r"중국어|일본어|한문|독일어|프랑스어|스페인어|러시아어|베트남어|아랍어|외국어"), "제2외국어·한문"),
    (re.compile(r"국어|문학|화법|작문|독서|언어와|고전"), "국어"),

    (re.compile(r"미술|디자인|조형|공예|음악|연주|합창|국악|예술"), "예술"),
    (re.compile(r"체육|운동|스포츠|건강"), "체육"),
]

# 교과가 아닌 영역. 이름 그대로 쓴다.
CREATIVE = "창의적 체험활동"
OTHER = "그 밖의 교과"


def family_of(subject: str) -> str:
    """과목 이름 하나를 교과군으로. 못 읽으면 `그 밖의 교과`."""
    name = (subject or "").strip()
    if not name:
        return OTHER
    for pattern, family in _RULES:
        if pattern.search(name):
            return family
    return OTHER
