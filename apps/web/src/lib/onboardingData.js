/** 계열별로 학과를 묶는다. 서버가 준 순서를 그대로 지킨다. */
export function groupTracksByField(tracks = []) {
  const byField = new Map();
  for (const t of tracks) {
    if (!byField.has(t.field)) byField.set(t.field, []);
    byField.get(t.field).push(t);
  }
  return FIELDS.filter((f) => byField.has(f.id)).map((f) => {
    const list = byField.get(f.id);
    // 카드에 적을 예시 학과 — 시드에서 뽑는다(따로 적어 두면 시드와 어긋난다).
    // 학과가 하나뿐인 계열은 이름을 통째로 쓴다. 앞말만 자르면 "인문 / 인문"
    // 처럼 계열 이름을 두 번 적은 꼴이 된다.
    const sample =
      list.length === 1
        ? list[0].name
        : list.slice(0, 3).map((t) => t.name.split(" / ")[0]).join(" · ");
    return { ...f, tracks: list, sample: sample === f.label ? "" : sample };
  });
}

